// Builds apps-script/App.html: the phone page from docs/ inlined into one file, so a tracker
// can serve its own page (doGet with no key) instead of relying on the hosted copy.
// Run: node tools/build_app.js   (deploy_script.ps1 runs it before pushing)
const fs = require('fs');
const path = require('path');

const docs = p => fs.readFileSync(path.join(__dirname, '..', 'docs', p), 'utf8');
let html = docs('index.html');
const css = docs('style.css');
const js = docs('app.js');

html = html
  .replace(/<link rel="manifest"[^>]*>\s*/, '')
  .replace(/<link rel="icon"[^>]*>\s*/, '')
  .replace(/<link rel="apple-touch-icon"[^>]*>\s*/, '')
  .replace('<link rel="stylesheet" href="style.css">', () => '<style>\n' + css + '\n</style>')
  .replace('<script src="app.js"></script>', () => '<script>\n' + js.replace(/<\/script/gi, '<\\/script') + '\n</script>');

for (const leftover of ['href="style.css"', 'src="app.js"', 'manifest.webmanifest']) {
  if (html.includes(leftover)) throw new Error('build_app: did not inline ' + leftover);
}
const out = path.join(__dirname, '..', 'apps-script', 'App.html');
fs.writeFileSync(out, '<!-- Generated by tools/build_app.js from docs/. Edit those, not this. -->\n' + html);
console.log('wrote ' + path.relative(process.cwd(), out) + ' (' + html.length + ' chars)');
